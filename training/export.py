"""Quantize the trained DS-CNN to int8, evaluate it the way the device runs
it, and generate the firmware's model sources.

    python training/export.py --run training/runs/dscnn --data <speech_commands_v0.02> \
        --test <speech_commands_test_set_v0.02>

Evaluation path for the int8 number = device path: C MFCC (ew_mfcc.c) ->
C quantizer with folded normalisation (ew_kws.c) -> int8 TFLite model.

Outputs:
  firmware/main/model/model_data.{cc,h}       flatbuffer as a C array
  firmware/main/model/model_settings.{c,h}    labels, feature stats, golden vector
  training/results/edgewake_kws_int8.tflite
  training/results/metrics.json
"""
import argparse
import datetime
import json
from pathlib import Path

import numpy as np

from data import LABELS, SpeechCommands, load_official_test_set, split_fingerprint
from frontend import REPO, Frontend


def representative_data(fe, ds, mean, std, n=1000):
    """Mix of clean and augmented training clips for calibrating activations."""
    rng = np.random.default_rng(123)
    pcm_a, _ = ds.make_set("training", rng, augment=True, limit=n // 2)
    pcm_c, _ = ds.make_set("training", rng, augment=False, limit=n // 2)
    feats = (fe.mfcc(np.concatenate([pcm_a, pcm_c])) - mean) / std
    for x in feats:
        yield [x[None, ..., None].astype(np.float32)]


def convert_int8(model, rep_fn):
    """Full-integer conversion with a fixed batch of 1: every shape is static,
    so the graph has no runtime shape arithmetic and TFLM plans it exactly."""
    import tensorflow as tf

    from model import build_dscnn

    # Rebuild with the canonical (short) layer names and a static batch of 1,
    # then copy the trained weights in.
    fixed = build_dscnn(input_shape=tuple(model.input.shape[1:]),
                        num_classes=model.output.shape[-1], batch_size=1)
    fixed.set_weights(model.get_weights())

    converter = tf.lite.TFLiteConverter.from_keras_model(fixed)
    converter.exclude_conversion_metadata = True
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = rep_fn
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    return converter.convert()


class Int8Model:
    def __init__(self, tflite_bytes, reference=False):
        """reference=True uses TFLite's reference kernels, the same ones TFLM
        implements (ESP-NN is tested against them), for bit-faithful results."""
        import tensorflow as tf

        resolver = (tf.lite.experimental.OpResolverType.BUILTIN_REF if reference
                    else tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
        self.interp = tf.lite.Interpreter(model_content=tflite_bytes,
                                          experimental_op_resolver_type=resolver)
        self.interp.allocate_tensors()
        self.inp = self.interp.get_input_details()[0]
        self.out = self.interp.get_output_details()[0]
        self.in_scale, self.in_zp = self.inp["quantization"]
        self.out_scale, self.out_zp = self.out["quantization"]

    def ops(self):
        return sorted({op["op_name"] for op in self.interp._get_ops_details()})

    def __call__(self, x_int8):
        """x_int8: (490,) or (49, 10) -> int8 scores (12,)."""
        self.interp.set_tensor(self.inp["index"], np.asarray(x_int8, np.int8).reshape(self.inp["shape"]))
        self.interp.invoke()
        return self.interp.get_tensor(self.out["index"]).reshape(-1).copy()


def c_array(name, data, per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return f"alignas(16) const unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def label_macro(label):
    return "EW_LABEL_" + label.strip("_").upper()


def write_firmware_sources(out_dir, tflite, mean, std, golden_pcm, golden_in, golden_scores, golden_cls, stamp):
    out_dir.mkdir(parents=True, exist_ok=True)
    header = f"/* GENERATED by training/export.py on {stamp} - do not edit. */\n"

    (out_dir / "model_data.h").write_text(header + """#ifndef MODEL_DATA_H
#define MODEL_DATA_H

#ifdef __cplusplus
extern "C" {
#endif

/* int8 DS-CNN TFLite flatbuffer (16-byte aligned for TFLM). */
extern const unsigned char g_kws_model[];
extern const unsigned int g_kws_model_len;

#ifdef __cplusplus
}
#endif

#endif /* MODEL_DATA_H */
""")
    (out_dir / "model_data.cc").write_text(
        header + '#include "model_data.h"\n\n' + c_array("g_kws_model", tflite) +
        f"const unsigned int g_kws_model_len = {len(tflite)};\n")

    macros = "\n".join(f"#define {label_macro(l):<20} {i}" for i, l in enumerate(LABELS))
    (out_dir / "model_settings.h").write_text(header + f"""#ifndef MODEL_SETTINGS_H
#define MODEL_SETTINGS_H

#include <stdint.h>

#include "ew_config.h"

/* Output classes, in model order. */
{macros}

extern const char *const ew_labels[EW_NUM_CLASSES];

/* Per-MFCC-coefficient mean and 1/std from the training set; folded into the
 * int8 input quantizer by ew_kws_init(). */
extern const float ew_feat_mean[EW_NUM_MFCC];
extern const float ew_feat_inv_std[EW_NUM_MFCC];

/* Golden vector for the boot / post-OTA self-test: one official test-set
 * clip ("{LABELS[golden_cls]}", chosen so its scores are not saturated), as raw
 * PCM, as the int8 features the host build of ew_mfcc.c + ew_kws.c computes
 * from it, and the int8 scores TFLite's reference kernels give for them. */
#define EW_GOLDEN_PCM_LEN {len(golden_pcm)}
extern const int16_t ew_golden_pcm[EW_GOLDEN_PCM_LEN];
extern const int8_t ew_golden_input[EW_INPUT_SIZE];
extern const int8_t ew_golden_scores[EW_NUM_CLASSES];
extern const int ew_golden_class;

#endif /* MODEL_SETTINGS_H */
""")

    def floats(v):
        return ", ".join(f"{x:.8e}f" for x in v)

    def ints(v, per_line=20):
        v = [int(x) for x in v]
        return ",\n    ".join(", ".join(str(x) for x in v[i:i + per_line]) for i in range(0, len(v), per_line))

    (out_dir / "model_settings.c").write_text(header + f"""#include "model_settings.h"

const char *const ew_labels[EW_NUM_CLASSES] = {{
    {", ".join(f'"{l}"' for l in LABELS)}
}};

const float ew_feat_mean[EW_NUM_MFCC] = {{
    {floats(mean)}
}};

const float ew_feat_inv_std[EW_NUM_MFCC] = {{
    {floats(1.0 / std)}
}};

const int16_t ew_golden_pcm[EW_GOLDEN_PCM_LEN] = {{
    {ints(golden_pcm)}
}};

const int8_t ew_golden_input[EW_INPUT_SIZE] = {{
    {ints(golden_in)}
}};

const int8_t ew_golden_scores[EW_NUM_CLASSES] = {{
    {ints(golden_scores)}
}};

const int ew_golden_class = {golden_cls};
""")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="training/runs/dscnn")
    ap.add_argument("--data", required=True)
    ap.add_argument("--test", required=True)
    ap.add_argument("--fw", default=str(REPO / "firmware" / "main" / "model"))
    ap.add_argument("--results", default=str(REPO / "training" / "results"))
    args = ap.parse_args()

    import keras

    from model import count_macs

    run = Path(args.run)
    results = Path(args.results)
    results.mkdir(parents=True, exist_ok=True)
    stats = np.load(run / "feature_stats.npz")
    mean, std = stats["mean"], stats["std"]
    model = keras.models.load_model(run / "best.keras")

    fe = Frontend()
    ds = SpeechCommands(args.data)

    print("converting to int8 ...")
    tflite = convert_int8(model, lambda: representative_data(fe, ds, mean, std))
    (results / "edgewake_kws_int8.tflite").write_bytes(tflite)
    q = Int8Model(tflite, reference=True)
    print(f"  {len(tflite)} bytes, ops: {q.ops()}")
    print(f"  input  scale={q.in_scale:.6f} zp={q.in_zp}   output scale={q.out_scale:.6f} zp={q.out_zp}")

    # Configure the C engine's quantizer with the model's input parameters.
    fe.kws_init(q.in_scale, q.in_zp, q.out_scale, q.out_zp, mean, 1.0 / std)

    def evaluate(pcm, y):
        mfcc = fe.mfcc(pcm)
        float_pred = model.predict(((mfcc - mean) / std)[..., None], batch_size=500, verbose=0).argmax(1)
        xq = fe.quantize(mfcc)
        scores = np.stack([q(x) for x in xq])
        return float_pred, scores.argmax(1), xq, scores

    print("evaluating on the official Speech Commands v0.02 test set ...")
    test_pcm, test_y = load_official_test_set(args.test)
    f_pred, q_pred, test_xq, test_scores = evaluate(test_pcm, test_y)
    float_acc = float((f_pred == test_y).mean())
    int8_acc = float((q_pred == test_y).mean())

    val_pcm, val_y = ds.make_set("validation", np.random.default_rng(2), augment=False)
    vf, vq, _, _ = evaluate(val_pcm, val_y)

    confusion = np.zeros((len(LABELS), len(LABELS)), int)
    for t, p in zip(test_y, q_pred):
        confusion[t, p] += 1
    per_class = {LABELS[i]: round(float(confusion[i, i] / confusion[i].sum()), 4) for i in range(len(LABELS))}

    # Golden vector: a correctly classified "on" clip whose int8 scores are NOT
    # saturated (top score well below 127, many classes above -128), so the
    # on-device comparison checks real values instead of two clipped extremes.
    on = LABELS.index("on")
    cands = np.where((test_y == on) & (q_pred == on))[0]
    top = test_scores[cands, on].astype(int)
    live = (test_scores[cands] > -128).sum(axis=1)
    ok = (top >= 40) & (top <= 115)
    pool = cands[ok] if ok.any() else cands
    g = pool[np.argmax(live[ok] if ok.any() else top)]
    print(f"golden clip #{g}: scores {test_scores[g].tolist()}")

    stamp = datetime.date.today().isoformat()
    write_firmware_sources(Path(args.fw), tflite, mean, std, test_pcm[g], test_xq[g].reshape(-1),
                           test_scores[g], on, stamp)

    metrics = {
        "date": stamp,
        "dataset": "Google Speech Commands v0.02, 12 classes (10 keywords + silence + unknown)",
        "test_set": "official speech_commands_test_set_v0.02",
        "test_clips": int(len(test_y)),
        "test_accuracy_float": round(float_acc, 4),
        "test_accuracy_int8": round(int8_acc, 4),
        "val_accuracy_float": round(float((vf == val_y).mean()), 4),
        "val_accuracy_int8": round(float((vq == val_y).mean()), 4),
        "per_class_accuracy_int8": per_class,
        "confusion_int8": confusion.tolist(),
        "labels": LABELS,
        "model_bytes": len(tflite),
        "params": int(model.count_params()),
        "macs_per_inference": count_macs(model),
        "ops": q.ops(),
        "input_quant": [float(q.in_scale), int(q.in_zp)],
        "output_quant": [float(q.out_scale), int(q.out_zp)],
        "train_split_fingerprint": split_fingerprint(ds.files["training"]),
        "frontend": {"sample_rate": fe.sample_rate, "frame": fe.frame_len, "hop": fe.hop,
                     "fft": fe.fft_len, "mel_bands": fe.mel_bands, "mfcc": fe.num_mfcc,
                     "frames": fe.num_frames},
    }
    (results / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print(json.dumps({k: metrics[k] for k in ["test_accuracy_float", "test_accuracy_int8",
                                              "val_accuracy_int8", "model_bytes", "params",
                                              "macs_per_inference"]}, indent=2))
    print("per-class (int8):", per_class)


if __name__ == "__main__":
    main()
